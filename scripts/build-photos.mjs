// Builds the shop's product photos from the originals in photos/originals/.
//
//   node scripts/build-photos.mjs
//
// For each photo it writes, into public/images/web/:
//   <name>.webp         the full original resolution (fallback, Google, link previews)
//   <name>-<width>.webp smaller copies, so each screen downloads the sharpest size it can show
// and records the widths in src/data/photo-widths.ts for the image loader
// (src/lib/image-loader.ts). Quality 90 WebP: visually the same as the original.
// Re-run after adding or replacing a photo in photos/originals/.
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ORIGINALS = path.join(ROOT, 'photos/originals');
const OUT = path.join(ROOT, 'public/images/web');
const WIDTHS = [480, 640, 960, 1280, 1600, 1920];
const QUALITY = 90;

// Site photo name → original. Mutton and Prawns pickles use the Chicken Pickle
// photo until their own photos arrive.
const PHOTOS = {
  'bobbatlu': 'bobbatlu.jpg',
  'chicken-pickle': 'chicken-pickle.jpg',
  'mutton-pickle': 'chicken-pickle.jpg',
  'prawns-pickle': 'chicken-pickle.jpg',
  'gift-box': 'gift-box.jpg',
  'guntur-malpuri': 'guntur-malpuri.jpg',
  'nellore-malai-khaja': 'nellore-malai-khaja.jpg',
  'pala-kova': 'pala-kova.jpg',
  'texas-limited-gift-box-closed': 'texas-limited-gift-box-closed.jpg',
  'texas-limited-gift-box-open': 'texas-limited-gift-box-open.jpg',
};

const manifest = {};
for (const [name, file] of Object.entries(PHOTOS)) {
  const source = readFileSync(path.join(ORIGINALS, file));
  const { width } = await sharp(source).rotate().metadata();
  const widths = [...WIDTHS.filter((w) => w < width), width];
  for (const w of widths) {
    const target = path.join(OUT, w === width ? `${name}.webp` : `${name}-${w}.webp`);
    await sharp(source)
      .rotate()
      .resize({ width: w, withoutEnlargement: true })
      .webp({ quality: QUALITY, effort: 6, smartSubsample: true })
      .toFile(target);
  }
  manifest[`/images/web/${name}.webp`] = widths;
  console.log(`${name}: ${widths.join(', ')}`);
}

writeFileSync(
  path.join(ROOT, 'src/data/photo-widths.ts'),
  `// Generated by scripts/build-photos.mjs — do not edit by hand.\n` +
  `/** Widths available for each product photo; the largest is the file without a width suffix. */\n` +
  `export const PHOTO_WIDTHS: Record<string, readonly number[]> = ${JSON.stringify(manifest, null, 2)};\n`,
);
