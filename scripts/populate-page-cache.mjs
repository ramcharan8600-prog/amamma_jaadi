// Copies the ready-built pages from an OpenNext build into Workers static assets,
// where the static-assets page cache (open-next.config.ts) reads them. This is what
// `opennextjs-cloudflare populateCache` does for that cache, without starting a
// local Workers runtime. Runs after `npm run cf-build` and before every
// `wrangler deploy` (wrangler.jsonc → build.command), so the pages ship whichever
// deploy command is used. With no build present it does nothing; if it were ever
// skipped, pages are simply rendered per visit as before.
//
// It also publishes the shop pages themselves as plain static files (sweets.html
// for /sweets, ...). Cloudflare serves a request that matches a static file
// without running the Worker, and static-file requests are free and unlimited,
// so browsing the shop costs nothing however many visits (or stuck tabs) there
// are. Only the live parts still run the Worker: /api (stock, cart, payments),
// /checkout and /admin. The Worker's security headers go with the files through
// the static-assets `_headers` file, built from the same src/lib/security-headers.mjs.
import { cpSync, existsSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import {
  HARDENING_HEADERS,
  PREVIEW_HOST_ROBOTS,
  productionSecurityHeaders,
} from '../src/lib/security-headers.mjs';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

/**
 * Pages that are the same for every visitor and are served as static files.
 * Every link to them must be a plain <a>, not next/link (see Header.tsx): a static
 * file can't answer the App Router's in-page data requests. Never list /checkout
 * or /admin here — those stay in the Worker.
 */
export const STATIC_SHOP_PAGES = ['/', '/sweets', '/pickles', '/gift-boxes', '/events', '/about'];

/** sweets.html for /sweets; index.html for / (Workers assets html_handling maps them). */
export function staticFileName(pagePath) {
  return pagePath === '/' ? 'index.html' : `${pagePath.slice(1)}.html`;
}

/** The `_headers` rules that give the static shop pages the Worker's security headers. */
export function staticPageHeaderRules(pages = STATIC_SHOP_PAGES) {
  const headers = [...HARDENING_HEADERS, ...productionSecurityHeaders()];
  const lines = ['', '# Shop pages served as static files (generated by scripts/populate-page-cache.mjs).'];
  for (const page of pages) {
    lines.push(page, ...headers.map(([name, value]) => `  ${name}: ${value}`));
  }
  lines.push('https://:worker.:account.workers.dev/*', `  X-Robots-Tag: ${PREVIEW_HOST_ROBOTS}`);
  return `${lines.join('\n')}\n`;
}

function main() {
  const cacheDir = path.join(ROOT, '.open-next/cache');
  const assetsDir = path.join(ROOT, '.open-next/assets');
  if (!existsSync(cacheDir)) {
    console.log('No OpenNext build found; page cache not copied.');
    return;
  }
  cpSync(cacheDir, path.join(assetsDir, 'cdn-cgi/_next_cache'), { recursive: true });
  console.log('Page cache copied into static assets.');

  const buildId = readFileSync(path.join(assetsDir, 'BUILD_ID'), 'utf8').trim();
  const published = [];
  for (const page of STATIC_SHOP_PAGES) {
    const entryName = page === '/' ? 'index' : page.slice(1);
    const entryFile = path.join(cacheDir, buildId, `${entryName}.cache`);
    const entry = existsSync(entryFile) ? JSON.parse(readFileSync(entryFile, 'utf8')) : null;
    if (entry?.type !== 'app' || typeof entry.html !== 'string' || (entry.meta?.status ?? 200) !== 200) {
      // The Worker still serves this page, as before; only the saving is lost.
      console.warn(`No ready-built page for ${page}; it stays in the Worker.`);
      continue;
    }
    writeFileSync(path.join(assetsDir, staticFileName(page)), entry.html);
    published.push(page);
  }

  // Rebuilt from public/_headers every run, so running twice never doubles the rules.
  const baseHeaders = readFileSync(path.join(ROOT, 'public/_headers'), 'utf8');
  writeFileSync(path.join(assetsDir, '_headers'), baseHeaders + staticPageHeaderRules(published));
  console.log(`Shop pages published as static files: ${published.join(' ')}`);
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) main();
